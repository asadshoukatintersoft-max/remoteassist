object Lang {
    private fun code(): String = Locale.getDefault().language

    fun tr(s: String): String {
        val m = when (code()) {
            "ur" -> UR
            "ar" -> AR
            else -> return s
        }
        return m[s] ?: s
    }

    fun tr(s: String, vararg a: Any): String {
        var r = tr(s)
        for (i in a.indices) r = r.replace("{" + i + "}", a[i].toString())
        return r
    }

